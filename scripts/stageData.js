/**
 * ── 난이도 곡선 (order 1~5 공통, 두 트랙 동일) ──────────────────
 *
 * 이전에는 모든 스테이지가 "시작 50 · 성공선 85 · 동일 채점"이어서 난이도가 우연에 맡겨졌다.
 * (좋은 발화 3번이면 3턴 만에 성공선을 넘고, 남은 12턴은 아무 의미가 없었다)
 * 이제 스테이지마다 아래 값을 주고, 채점 프롬프트와 플레이 화면이 이 값을 읽는다.
 *
 *   startGauge   시작 게이지 — 뒤로 갈수록 낮게 (상대가 처음부터 더 닫혀 있다)
 *   successLine  설득 성공선 — 뒤로 갈수록 높게
 *   resistance   1~5. 캐릭터가 얼마나 완고한가. 턴당 점수 상한을 함께 조인다.
 *   targetTurns  "이 정도 턴이면 성공선에 닿도록" 설계된 기준 턴 수.
 *                채점이 이 궤도와 비교해 너무 빠르면 엄격해지고, 뒤처지면 평소대로 준다.
 *   maxDelta/minDelta  턴당 점수 상·하한. 저항이 셀수록 한 방에 뒤집을 수 없다.
 *   floorBonus   "방향만 맞아도 최소 이만큼은 준다"의 하한. 초반 스테이지에만 준다.
 *                (이 값이 0이면 성의만으로는 게이지가 오르지 않는다 = 진짜 실패가 가능하다)
 *   timeLimit/maxMessages  스테이지별 제한. 뒤로 갈수록 넉넉하게.
 *
 * 합계 약 44분 — 한 트랙을 40~50분 수업에 맞춘 값이다.
 */
/*
 * [설계 메모] 턴당 상한(maxDelta)을 난이도별로 크게 벌리지 않는 이유
 *   필요 평균 점수 = (successLine - startGauge) / targetTurns 인데, 이 값을 모든 단계에서
 *   +3.3 ~ +3.6 정도로 비슷하게 맞췄다. 즉 "몇 점씩 올려야 하는가"는 어디서나 비슷하고,
 *   난이도는 **그 점수를 따내기가 얼마나 어려운가**(resistance)와
 *   **성의만으로 점수가 나오는가**(floorBonus)에서 나온다.
 *   상한만 키우면 한 방에 뒤집히는 운 게임이 되고, 상한만 줄이면 그냥 지루해진다.
 *
 *   EP1: 25점 / 7턴  = 턴당 +3.6 필요 (저항1·성의 보너스 있음 → 쉽게 따인다)
 *   EP5: 50점 / 14턴 = 턴당 +3.6 필요 (저항5·보너스 없음 → 제대로 짚어야만 따인다)
 *
 * [breakdownLine — 대화 결렬선]
 *   게이지가 이 값 이하로 떨어진 채 두 턴이 더 지나면 스테이지가 "결렬"로 끝난다.
 *   시뮬레이션에서 게이지가 0을 찍고도 9턴을 더 다그치는 장면이 나왔는데,
 *   이미 끝난 대화를 붙잡고 있는 것은 학습도 재미도 아니다.
 *   실제 설득에서도 상대는 자리를 뜬다 — 그 선을 게임에도 둔다.
 */
