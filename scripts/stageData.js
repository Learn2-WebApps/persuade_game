/**
 * 시나리오 배열 → seed가 쓰는 { id, data } 형태로 변환 (문서 id는 order 기준).
 * 난이도는 order에 따라 여기서 한 번에 주입한다 — 시나리오마다 적어 두면 곡선이 어긋난다.
 * (시나리오가 difficulty를 직접 지정했다면 그 값이 우선한다 — 예외를 둘 때만 쓸 것)
 */
const toStageDocs = (scenarios) =>
  scenarios.map((s) => ({
    id: `stage${s.order}`,
    data: { ...s, difficulty: s.difficulty || { ...DIFFICULTY_CURVE[s.order] } },
  }));

